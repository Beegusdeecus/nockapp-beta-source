import { readFile, access, readdir } from 'node:fs/promises';
import assert from 'node:assert/strict';

const manifest = JSON.parse(await readFile('dist/manifest.json', 'utf8'));
assert.equal(manifest.manifest_version, 3);
assert.deepEqual([...manifest.permissions].sort(), ['activeTab', 'contextMenus', 'sidePanel', 'storage', 'nativeMessaging', 'webRequest'].sort());
assert.deepEqual([...manifest.optional_host_permissions].sort(), ['https://x.com/*', 'https://api.x.com/*', 'https://abs.twimg.com/*'].sort());
assert.equal(manifest.host_permissions, undefined);
assert.equal(manifest.content_scripts, undefined);
assert.match(manifest.content_security_policy.extension_pages, /connect-src 'none'/);
await access(`dist/${manifest.background.service_worker}`);
await access(`dist/${manifest.side_panel.default_path}`);
await access('dist/x-connect.html');
await access('dist/public-post.html');
await access('dist/public-wallet.html');
await access('dist/public-tickets.html');
for (const icon of Object.values(manifest.icons)) await access(`dist/${icon}`);
const html = await readFile('dist/sidepanel.html', 'utf8');
assert(!/<script(?![^>]*\bsrc=)[^>]*>\s*\S/i.test(html), 'MV3 must not contain inline JavaScript');
for (const file of await readdir('dist/assets')) assert(!file.endsWith('.map'));
console.log('Manifest, permissions, CSP, entry points and icons checked.');
const firefox = JSON.parse(await readFile('dist-firefox/manifest.json', 'utf8'));
assert.deepEqual(firefox.permissions, manifest.permissions.filter((name) => name !== 'sidePanel'));
assert.deepEqual(firefox.optional_host_permissions, manifest.optional_host_permissions);
assert.equal(firefox.host_permissions, undefined);
assert.equal(firefox.content_scripts, undefined);
assert.equal(firefox.background.service_worker, undefined);
assert.deepEqual(firefox.background.scripts, ['background.js']);
assert.equal(firefox.background.type, 'module');
assert.equal(firefox.sidebar_action.default_panel, 'sidepanel.html');
assert.equal(firefox.browser_specific_settings.gecko.id, 'nockapp@beegus.local');
assert.deepEqual(firefox.content_security_policy, manifest.content_security_policy);
await access('dist-firefox/background.js');
await access('dist-firefox/x-connect.html');
await access('dist-firefox/public-post.html');
await access('dist-firefox/public-wallet.html');
await access('dist-firefox/public-tickets.html');
console.log('Firefox manifest, permissions and shared entry points checked.');
